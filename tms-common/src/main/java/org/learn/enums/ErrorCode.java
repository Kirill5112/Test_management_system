package org.learn.enums;

public enum ErrorCode {

    PROJECT_NOT_FOUND("PROJECT_NOT_FOUND"),
    PROJECT_KEY_EXISTS("PROJECT_KEY_EXISTS"),
    BUG_REPORT_NOT_FOUND("BUG_REPORT_NOT_FOUND"),
    REPOSITORY_UNAVAILABLE("REPOSITORY_UNAVAILABLE"),
    USER_NOT_FOUND("USER_NOT_FOUND"),
    TEST_RESULT_NOT_FOUND("TEST_RESULT_NOT_FOUND"),
    USERNAME_ALREADY_EXISTS("USERNAME_ALREADY_EXISTS"),
    EMAIL_ALREADY_EXISTS("EMAIL_ALREADY_EXISTS"),
    TEST_RESULT_ALREADY_EXISTS("TEST_RESULT_ALREADY_EXISTS"),
    TEST_RUN_NOT_FOUND("TEST_RUN_NOT_FOUND"),
    TEST_RUN_INVALID_STATE("TEST_RUN_INVALID_STATE");
    private final String code;
    ErrorCode(String code) {
        this.code = code;
    }

    public String getCode() {
        return code;
    }
}
